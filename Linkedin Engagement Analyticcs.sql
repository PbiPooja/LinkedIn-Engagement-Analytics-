--LEADERBOARD OF CREATORS BASED ON OVERALL ENGAGEMENT (LIKES+COMMENTS+SHARES) 
WITH X AS ( SELECT U.user_id,U.user_name,U.country,
 SUM(P.likes+P.comments+P.shares) AS ENGAGMENT

 FROM [dbo].[posts] P INNER JOIN [dbo].[users] U
 ON P.user_id =U.user_id

 GROUP BY U.user_id, U.user_name,U.country)

 SELECT *, DENSE_RANK () OVER ( ORDER BY ENGAGMENT DESC ) AS RANKING
 FROM X;

